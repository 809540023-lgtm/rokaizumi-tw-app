/** 讀取上次選擇的語言；沒有的話用繁中（本站主要客群在台灣） */
function initialLanguage(): Language {
  if (typeof window === 'undefined') return 'ja';
  try {
    const saved = window.localStorage.getItem(STORAGE_KEY);
    if (saved && saved in translations) return saved as Language;
  } catch {
    // Storage can be unavailable in private or restricted browsing.
  }
  return 'ja';
}

export function documentLanguage(language: Language): string {
  return { zh: 'zh-TW', cn: 'zh-CN', ja: 'ja', en: 'en' }[language];
}

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [language, setLanguageState] = useState<Language>(initialLanguage);

  useEffect(() => {
    document.documentElement.lang = documentLanguage(language);
  }, [language]);

  // 語言選擇要跨頁面保留，否則每次換頁都會跳回預設值
  const setLanguage = (lang: Language) => {
    setLanguageState(lang);
    try {
      window.localStorage.setItem(STORAGE_KEY, lang);
    } catch {
      /* 隱私模式下忽略 */
    }
  };

  // 遞補鏈：選定語言 → 繁中 → key 本身。
  // 直接吐 key（例如畫面上出現 "cart.addSuccess"）對使用者毫無意義，
  // 所以缺翻譯時寧可顯示繁中。
  const t = (key: string): string => {
    const table = translations[language] as Record<string, string> | undefined;
    return table?.[key] ?? (translations.zh as Record<string, string>)[key] ?? key;
  };

  return (
    <LanguageContext.Provider value={{ language, setLanguage, t }}>
      {children}
    </LanguageContext.Provider>
  );
}

export function useLanguage() {
  const context = useContext(LanguageContext);
  if (!context) {
    throw new Error('useLanguage must be used within LanguageProvider');
  }
  return context;
}
